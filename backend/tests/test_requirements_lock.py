"""Guards the backend dependency lockfile against drift.

The Docker image must install pinned versions from requirements.txt (compiled from
pyproject.toml) so image builds are reproducible, and the test venv must install under the
same pins so the suite exercises what the image ships. These checks fail when a direct runtime
dependency is added to pyproject.toml without regenerating the lock, when the lock was compiled
on a different Python than the image runs, or when the Dockerfile or the venv provisioning
stops installing from it.
"""
import re
import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parents[1]
LOCKFILE = BACKEND / "requirements.txt"
DOCKERFILE = BACKEND / "Dockerfile"
COMMON_SH = BACKEND.parent / "scripts" / "common.sh"


def _direct_runtime_dependencies() -> set[str]:
    pyproject = tomllib.loads((BACKEND / "pyproject.toml").read_text(encoding="utf-8"))
    return {
        canonicalize_name(Requirement(spec).name)
        for spec in pyproject["project"]["dependencies"]
    }


def _locked_pins() -> dict[str, str]:
    # Key: canonical package name  Value: the version specifier it was pinned with
    pins: dict[str, str] = {}
    for line in LOCKFILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-")):
            continue
        requirement = Requirement(line)
        pins[canonicalize_name(requirement.name)] = str(requirement.specifier)
    return pins


def test_lockfile_pins_every_direct_runtime_dependency():
    assert LOCKFILE.exists(), "backend/requirements.txt lockfile is missing"
    pins = _locked_pins()
    for name in sorted(_direct_runtime_dependencies()):
        assert name in pins, f"{name} is in pyproject.toml but not in requirements.txt"
        assert pins[name].startswith("=="), f"{name} is not pinned exactly: {pins[name]}"


def test_dockerfile_installs_from_lockfile():
    dockerfile = DOCKERFILE.read_text(encoding="utf-8")
    assert "requirements.txt" in dockerfile, (
        "Dockerfile does not install dependencies from the requirements.txt lockfile"
    )


def test_lockfile_compiled_on_the_image_python():
    image_python = re.search(
        r"^FROM python:(\d+\.\d+)", DOCKERFILE.read_text(encoding="utf-8"), re.MULTILINE
    )
    assert image_python, "Dockerfile does not build on a python:<major.minor> image"
    lock_python = re.search(
        r"autogenerated by pip-compile with Python (\d+\.\d+)",
        LOCKFILE.read_text(encoding="utf-8"),
    )
    assert lock_python, "requirements.txt lacks the pip-compile header naming its Python"
    assert lock_python.group(1) == image_python.group(1), (
        f"requirements.txt was compiled on Python {lock_python.group(1)} but the image runs "
        f"{image_python.group(1)}; regenerate it with scripts/lock.sh"
    )


def test_venv_installs_under_the_lockfile_pins():
    common_sh = COMMON_SH.read_text(encoding="utf-8")
    assert "--constraint requirements.txt" in common_sh, (
        "scripts/common.sh provisions backend/.venv without constraining it to requirements.txt"
    )
